"""FastAPI web app for the Landscape Generator: serves the front end in static/ and the JSON API under /api.

Run with `python run_web.py` (http://127.0.0.1:8162, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below.

Everything here is read from the terrain package (EnhancedTerrainParams defaults, DEFAULT_FEATURES,
SEASONAL_COLORS) or computed by it (reference landscapes); the browser generates landscapes with a JS port
of the same code (static/terrain_engine.js) that reproduces the Python maps for a given seed.
"""
from dataclasses import asdict
from pathlib import Path
from typing import Dict

import numpy as np
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from matplotlib import colormaps
from pydantic import BaseModel

from ..biomes import SEASONAL_COLORS
from ..features import DEFAULT_FEATURES
from ..params import EnhancedTerrainParams, Season
from .reference import CASE_BY_NAME, CASES, MAX_SIZE, run

STATIC = Path(__file__).resolve().parent / "static"
ROOT = Path(__file__).resolve().parents[2]

app = FastAPI(title="Landscape Generator")
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


def _summary() -> str:
    readme = (ROOT / "README.md").read_text(encoding="utf-8").split("\n\n")
    return " ".join(readme[1].split()) if len(readme) > 1 else ""


@app.get("/api/info")
def info():
    """Project summary, parameter defaults, seasons and the feature catalogue."""
    defaults = {k: (v.value if isinstance(v, Season) else v) for k, v in asdict(EnhancedTerrainParams()).items()}
    return {
        "title": "Landscape Generator",
        "summary": _summary(),
        "defaults": defaults,
        "seasons": [{"key": s.value, "name": s.name.title(), "colors": SEASONAL_COLORS[s]} for s in Season],
        "features": [{"key": k, "name": f.name, "height_modifier": f.height_modifier,
                      "moisture_modifier": f.moisture_modifier, "color_map": f.color_map}
                     for k, f in DEFAULT_FEATURES.items()],
        "counts": {"features": len(DEFAULT_FEATURES), "seasons": len(Season), "params": len(defaults)},
    }


@app.get("/api/colormaps")
def colormaps_lut():
    """The matplotlib colormaps of the Python analysis views ('terrain' for height, 'YlGnBu' for moisture),
    as 256 hex colours each."""
    out = {}
    for name in ("terrain", "YlGnBu"):
        rgb = colormaps[name](np.linspace(0, 1, 256))[:, :3]
        out[name] = ["#%02x%02x%02x" % tuple(int(round(c * 255)) for c in row) for row in rgb]
    return out


@app.get("/api/reference")
def reference_list():
    """The seeded Python reference landscapes shown on the Verify page."""
    return CASES


@app.get("/api/reference/{name}")
def reference(name: str):
    """One reference landscape generated by the Python package (height map + colour map)."""
    if name not in CASE_BY_NAME:
        raise HTTPException(404, f"unknown reference {name!r}")
    c = CASE_BY_NAME[name]
    return {"name": name, **run(c["params"], c["seed"])}


class GenerateRequest(BaseModel):
    seed: int = 42
    params: Dict = {}


@app.post("/api/generate")
def generate(req: GenerateRequest):
    """Run the Python generator for any parameters (local app only; size up to MAX_SIZE)."""
    if req.seed < 0:
        raise HTTPException(422, "seed must be non-negative")
    try:
        return {"name": "custom", **run(req.params, req.seed)}
    except (ValueError, KeyError, TypeError) as e:
        raise HTTPException(422, str(e))


@app.get("/api/limits")
def limits():
    return {"reference_max_size": MAX_SIZE}


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/colormaps", "/reference", "/limits"] + [f"/reference/{c['name']}" for c in CASES]
