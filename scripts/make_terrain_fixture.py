"""Write tests/fixtures/terrain_reference.json: values computed by the Python package that the
browser port must reproduce (checked by terrain/web/static/terrain_engine.test.mjs and
np_random.test.mjs; tests/test_web.py checks this file is still current).

Run: python scripts/make_terrain_fixture.py
"""
import json
import sys
from dataclasses import asdict
from pathlib import Path

import numpy as np
from scipy.ndimage import _filters

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from terrain.features import DEFAULT_FEATURES  # noqa: E402
from terrain.generator import TerrainGenerator  # noqa: E402
from terrain.params import EnhancedTerrainParams, Season  # noqa: E402
from terrain.pipeline import generate_landscape  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "terrain_reference.json"
SEEDS = [0, 42, 2**40 + 5]
CASES = [  # (name, seed, overrides, store full arrays)
    ("summer-40", 42, dict(size=40), True),
    ("winter-32", 7, dict(size=32, season=Season.WINTER, feature_density=0.25, octaves=4,
                          persistence=0.6, base_frequency=3.0, sea_level=0.4), False),
    ("spring-32", 123, dict(size=32, season=Season.SPRING, feature_density=0.2), False),
    ("fall-24", 2024, dict(size=24, season=Season.AUTUMN, lacunarity=2.5, mountain_level=0.6), False),
]
SAMPLE = 64  # sampled values per map for the cases without full arrays


def floats(a) -> list:
    return [float("%.12g" % v) for v in np.asarray(a).ravel()]


def rng_section() -> list:
    out = []
    for s in SEEDS:
        raw = np.random.PCG64(s).random_raw(5)
        g = np.random.default_rng(s)
        uni = g.random(5).tolist()
        nor = g.normal(0, 0.1, 5).tolist()
        big = g.standard_normal(200_000)
        out.append({"seed": s, "seedseq": np.random.SeedSequence(s).generate_state(8).tolist(),
                    "raw": [str(int(v)) for v in raw], "random": uni, "normal": nor,
                    "big_sum": float(big.sum()), "big_last": float(big[-1]),
                    "big_absmax": float(np.abs(big).max())})
    return out


def landscape_case(name, seed, overrides, full) -> dict:
    p = EnhancedTerrainParams(**overrides)
    params = {k: (v.value if isinstance(v, Season) else v) for k, v in asdict(p).items()}
    land = generate_landscape(p, seed=seed)
    n = p.size
    rgb = np.round(land.color_map * 255).astype(int).reshape(-1, 3)
    palette = sorted({"#%02X%02X%02X" % tuple(c) for c in rgb})
    colors = "".join(chr(65 + palette.index("#%02X%02X%02X" % tuple(c))) for c in rgb)
    idx = np.linspace(0, n * n - 1, SAMPLE).astype(int)
    case = {"name": name, "seed": seed, "params": params, "snow_level": p.snow_level,
            "palette": palette, "colors": colors,
            "mask_sums": {k: float(m.sum()) for k, m in land.feature_masks.items()}}
    for key, arr in (("base_height", land.base_height), ("height", land.height_map),
                     ("moisture", land.moisture_map)):
        case[key] = floats(arr) if full else {"index": idx.tolist(), "values": floats(arr.ravel()[idx]),
                                              "sum": float(arr.sum())}
    return case


def build_fixture() -> dict:
    gen = TerrainGenerator(EnhancedTerrainParams(size=32), seed=3)
    return {
        "note": "Generated by scripts/make_terrain_fixture.py from the Python terrain package.",
        "numpy": np.__version__,
        "defaults": {k: (v.value if isinstance(v, Season) else v)
                     for k, v in asdict(EnhancedTerrainParams()).items()},
        "features": [{"key": k, "name": f.name, "height_modifier": f.height_modifier,
                      "moisture_modifier": f.moisture_modifier, "color_map": f.color_map}
                     for k, f in DEFAULT_FEATURES.items()],
        "rng": rng_section(),
        "kernels": {str(s): _filters._gaussian_kernel1d(s, 0, int(4.0 * s + 0.5)).tolist() for s in (1.0, 2.0)},
        "noise_32_f4_seed3": floats(gen.generate_noise((32, 32), 4.0)),
        "cases": [landscape_case(*c) for c in CASES],
    }


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build_fixture(), separators=(",", ":")))
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} kB)")
