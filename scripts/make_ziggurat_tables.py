"""Write terrain/web/static/ziggurat_tables.js from NumPy's ziggurat_constants.h.

The JS port of numpy.random.Generator.normal (np_random.js) needs NumPy's exact ziggurat
tables (ki_double, wi_double, fi_double). They live in NumPy's C sources, not in the
installed package, so pass the header path, e.g. from a NumPy source checkout:

    python scripts/make_ziggurat_tables.py numpy/random/src/distributions/ziggurat_constants.h

The node test (np_random.test.mjs) checks the resulting normals against NumPy draws.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "terrain" / "web" / "static" / "ziggurat_tables.js"


def table(src: str, name: str) -> list:
    body = re.search(r"%s\[\]\s*=\s*\{(.*?)\};" % name, src, re.S).group(1)
    vals = [v.strip().rstrip("ULL").rstrip("f") for v in body.split(",") if v.strip()]
    assert len(vals) == 256, (name, len(vals))
    if name.startswith("ki"):
        return [str(int(v, 16)) for v in vals]  # < 2**52, exact as JS numbers
    return vals


def main() -> None:
    src = Path(sys.argv[1]).read_text()
    lines = ["// NumPy's ziggurat tables for the standard normal (numpy/random/src/distributions/",
             "// ziggurat_constants.h, NumPy BSD-3-Clause licence). Generated by scripts/make_ziggurat_tables.py.",
             "// ki values are integers below 2**52, so they are exact as JS numbers."]
    for name in ("ki_double", "wi_double", "fi_double"):
        vals = table(src, name)
        lines.append(f"export const {name.upper()} = new Float64Array([")
        lines += ["  " + ", ".join(vals[i:i + 4]) + "," for i in range(0, 256, 4)]
        lines.append("]);")
    lines.append("export const ZIGGURAT_NOR_R = 3.6541528853610087963519472518;")
    lines.append("export const ZIGGURAT_NOR_INV_R = 0.27366123732975827203338247596;")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
